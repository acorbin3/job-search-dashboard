def load_registry() -> dict:
    if REGISTRY.exists():
        return json.loads(REGISTRY.read_text())
    return {}


def save_registry(reg: dict):
    tmp = REGISTRY.with_suffix(".tmp")
    tmp.write_text(json.dumps(reg, indent=1, sort_keys=True))
    tmp.replace(REGISTRY)


def build_colleges_json(reg: dict, include_generic=True) -> dict:
    """Collapse the registry into the {ats: [config]} shape scrape.py scans."""
    out = {"_comment": "Generated by colleges/discover.py from IPEDS + each school's site. "
                       "Edit colleges_registry.json (or re-run discovery) rather than this file."}
    for key, lst in AGGREGATORS.items():
        out[key] = list(lst)
    seen = set()
    for rec in sorted(reg.values(), key=lambda r: r["name"]):
        if rec.get("status") not in ("ok", "generic"):
            continue
        if rec["status"] == "generic" and not include_generic:
            continue
        for c in (rec.get("configs") or [rec.get("config")]):
            if not c:
                continue
            cfg = dict(c)
            ats = cfg.pop("ats", None)
            if not ats:
                continue
            cfg.setdefault("slug", rec["name"])
            cfg.setdefault("name", rec["name"])
            cfg.setdefault("location", f"{rec.get('city','')}, {rec.get('state','')}".strip(", "))
            cfg["state"] = rec.get("state", "")
            if ats in AGGREGATORS:      # seeded above; a school merely linking to one is not a board
                continue
            dedupe = (ats, json.dumps({k: v for k, v in cfg.items() if k not in ("slug", "name", "location", "state")}, sort_keys=True))
            if dedupe in seen:  # several campuses sharing one board
                continue
            seen.add(dedupe)
            if ats in ("icims", "applicantpro", "greenhouse", "lever", "bamboohr", "jobvite", "smartrecruiters", "workable"):
                out.setdefault(ats, []).append(cfg.get("slug_id") or cfg["slug"])
            else:
                out.setdefault(ats, []).append(cfg)
    return out


def write_colleges_json(reg: dict):
    COLLEGES.write_text(json.dumps(build_colleges_json(reg), indent=1))
    return COLLEGES
